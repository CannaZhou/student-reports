// 只有兔＝12（第 13 列）那一列满足 94 只脚。三行分别是：行0 鸡的只数、行1 总脚数、行2 √/×。
function g6l3EnumKeys() {
  const k = { 0: {}, 1: {}, 2: {} };
  for (let i = 1; i <= G6L3_TRIES; i++) {
    const tu = i - 1, ji = G6L3_TRIES - i;
    k[0]['c' + i] = String(ji);
    k[1]['c' + i] = String(ji * 2 + tu * 4);
    k[2]['c' + i] = (tu === 12) ? '√' : '×';
  }
  return k;
}

