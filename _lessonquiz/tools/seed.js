// 兔的只数 0~35：印在表头下面当只读行，学生不用把 0~35 重敲一遍（相当于 Excel 里拖出来的那一行）
function g6l3RabbitRow() {
  const row = { lab: '兔的只数' };
  for (let i = 1; i <= G6L3_TRIES; i++) row['c' + i] = String(i - 1);
  return row;
}

